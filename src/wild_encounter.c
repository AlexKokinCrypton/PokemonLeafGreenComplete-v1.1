static bool8 TryPLGFireRedExclusive(u8 area, u8 rod, u8 selectedSlot, u16 *species, u8 *level)
{
#ifdef LEAFGREEN
    u8 commonSlot;
    u8 commonRate;
    u16 matches[8];
    u8 matchCount = 0;
    u32 i;

    switch (area)
    {
    case WILD_AREA_LAND:
        commonSlot = 0;
        commonRate = 20;
        break;
    case WILD_AREA_WATER:
    case WILD_AREA_ROCKS:
        commonSlot = 0;
        commonRate = 60;
        break;
    case WILD_AREA_FISHING:
        if (rod == OLD_ROD) { commonSlot = 0; commonRate = 70; }
        else if (rod == GOOD_ROD) { commonSlot = 2; commonRate = 60; }
        else { commonSlot = 5; commonRate = 40; }
        break;
    default:
        return FALSE;
    }

    if (selectedSlot != commonSlot)
        return FALSE;

    for (i = 0; i < ARRAY_COUNT(sPLGExclusiveEncounters); i++)
    {
        const struct PLGExclusiveEncounter *entry = &sPLGExclusiveEncounters[i];
        if (entry->mapGroup == gSaveBlock1Ptr->location.mapGroup
         && entry->mapNum == gSaveBlock1Ptr->location.mapNum
         && entry->area == area
         && entry->rod == rod
         && matchCount < ARRAY_COUNT(matches))
            matches[matchCount++] = i;
    }

    if (matchCount != 0)
    {
        // Each matching FireRed-exclusive species receives an effective 3% chance
        // by borrowing probability from the common slot for this encounter table.
        u8 roll = Random() % commonRate;
        if (roll < matchCount * 3)
        {
            const struct PLGExclusiveEncounter *entry = &sPLGExclusiveEncounters[matches[roll / 3]];
            *species = entry->species;
            *level = entry->minLevel + (Random() % (entry->maxLevel - entry->minLevel + 1));
            return TRUE;
        }
    }
#endif
    return FALSE;
}

#define WILD_CHECK_REPEL    0x1
#define WILD_CHECK_KEEN_EYE 0x2

static bool8 TryGeneratePLGAlteringCaveMon(u8 flags)
{
    static const u16 sSpecies[] = {
        SPECIES_ZUBAT, SPECIES_MAREEP, SPECIES_PINECO, SPECIES_HOUNDOUR, SPECIES_TEDDIURSA,
        SPECIES_AIPOM, SPECIES_SHUCKLE, SPECIES_STANTLER, SPECIES_SMEARGLE
    };
    static const u8 sMinLevels[] = {6, 3, 19, 12, 18, 18, 18, 18, 18};
    static const u8 sMaxLevels[] = {16, 13, 29, 22, 28, 28, 28, 28, 28};
    u8 roll;
    u8 idx;
    u8 level;

    if (gSaveBlock1Ptr->location.mapGroup != MAP_GROUP(MAP_SIX_ISLAND_ALTERING_CAVE)
     || gSaveBlock1Ptr->location.mapNum != MAP_NUM(MAP_SIX_ISLAND_ALTERING_CAVE))
        return FALSE;

    // 20% Zubat, 10% each of the eight restored Wonder Spot species.
    roll = Random() % 100;
    idx = (roll < 20) ? 0 : ((roll - 20) / 10) + 1;
    level = sMinLevels[idx] + (Random() % (sMaxLevels[idx] - sMinLevels[idx] + 1));
    if (flags == WILD_CHECK_REPEL && !IsWildLevelAllowedByRepel(level))
        return TRUE;
    GenerateWildMon(sSpecies[idx], level, 0);
    return TRUE;
}

static bool8 TryGenerateWildMon(const struct WildPokemonInfo * info, u8 area, u8 flags)
{
    u8 slot = 0;
    if (area == WILD_AREA_LAND
     && gSaveBlock1Ptr->location.mapGroup == MAP_GROUP(MAP_SIX_ISLAND_ALTERING_CAVE)
     && gSaveBlock1Ptr->location.mapNum == MAP_NUM(MAP_SIX_ISLAND_ALTERING_CAVE))
        return TryGeneratePLGAlteringCaveMon(flags);
    u8 level;
    switch (area)
    {
    case WILD_AREA_LAND:
        slot = AdjustPLGSafariLandSlot(info, ChooseWildMonIndex_Land());
        break;
    case WILD_AREA_WATER:
        slot = ChooseWildMonIndex_WaterRock();
        break;
    case WILD_AREA_ROCKS:
        slot = ChooseWildMonIndex_WaterRock();
        break;
    }
    level = ChooseWildMonLevel(&info->wildPokemon[slot]);
    {
        u16 species = info->wildPokemon[slot].species;
        u8 plgLevel = level;
        if (TryPLGFireRedExclusive(area, PLG_ROD_NONE, slot, &species, &plgLevel))
            level = plgLevel;
        if (flags == WILD_CHECK_REPEL && !IsWildLevelAllowedByRepel(level))
            return FALSE;
        GenerateWildMon(species, level, slot);
    }
    return TRUE;
}

static bool8 IsPLGSafariFishingInfo(const struct WildPokemonInfo *info)
{
#ifdef LEAFGREEN
    return (info == &sSafariZoneCenter_LeafGreen_FishingMonsInfo
         || info == &sSafariZoneEast_LeafGreen_FishingMonsInfo
         || info == &sSafariZoneNorth_LeafGreen_FishingMonsInfo
         || info == &sSafariZoneWest_LeafGreen_FishingMonsInfo);
#else
    return FALSE;
#endif
}

static u8 ChoosePLGSafariSuperRodIndex(void)
{
    // LeafGreen Complete v1.1: Dragonair is 3% in all four Safari areas.
    // Borrow the extra 2 percentage points from the common Super Rod slot 5:
    // slot 5 = 38%, slot 6 = 40%, slot 7 = 15%, slot 8 = 4%, slot 9 = 3%.
    u8 rand = Random() % 100;

    if (rand < 38)
        return 5;
    if (rand < 78)
        return 6;
    if (rand < 93)
        return 7;
    if (rand < 97)
        return 8;
    return 9;
}

static u16 GenerateFishingEncounter(const struct WildPokemonInfo * info, u8 rod)
{
    u8 slot;
    u8 level;
    u16 species;

    if (rod == SUPER_ROD && IsPLGSafariFishingInfo(info))
        slot = ChoosePLGSafariSuperRodIndex();
    else
        slot = ChooseWildMonIndex_Fishing(rod);

    level = ChooseWildMonLevel(&info->wildPokemon[slot]);
    species = info->wildPokemon[slot].species;
    TryPLGFireRedExclusive(WILD_AREA_FISHING, rod, slot, &species, &level);
    GenerateWildMon(species, level, slot);
    return species;
}

static bool8 DoWildEncounterRateDiceRoll(u16 encounterRate)
{
    if (WildEncounterRandom() % MAX_ENCOUNTER_RATE < encounterRate)
        return TRUE;
    return FALSE;
}

static bool8 DoWildEncounterRateTest(u32 encounterRate, bool8 ignoreAbility)
{
    encounterRate *= 16;
    if (TestPlayerAvatarFlags(PLAYER_AVATAR_FLAG_MACH_BIKE | PLAYER_AVATAR_FLAG_ACRO_BIKE))
        encounterRate = encounterRate * 80 / 100;
    encounterRate += sWildEncounterData.encounterRateBuff * 16 / 200;
    ApplyFluteEncounterRateMod(&encounterRate);
    ApplyCleanseTagEncounterRateMod(&encounterRate);
    if (!ignoreAbility)
    {
        switch (sWildEncounterData.abilityEffect)
        {
        case 1:
            encounterRate /= 2;
            break;
        case 2:
            encounterRate *= 2;
            break;
        }
    }
    if (encounterRate > MAX_ENCOUNTER_RATE)
        encounterRate = MAX_ENCOUNTER_RATE;
    return DoWildEncounterRateDiceRoll(encounterRate);
}

static u8 GetAbilityEncounterRateModType(void)
{
    sWildEncounterData.abilityEffect = 0;
    if (!GetMonData(&gPlayerParty[0], MON_DATA_SANITY_IS_EGG))
    {
        u8 ability = GetMonAbility(&gPlayerParty[0]);
        if (ability == ABILITY_STENCH)
            sWildEncounterData.abilityEffect = 1;
        else if (ability == ABILITY_ILLUMINATE)
            sWildEncounterData.abilityEffect = 2;
    }
    return sWildEncounterData.abilityEffect;
}

static bool8 DoGlobalWildEncounterDiceRoll(void)
{
    if ((Random() % 100) >= 60)
        return FALSE;
    return TRUE;
}

bool8 StandardWildEncounter(u32 currMetatileAttrs, u16 previousMetatileBehavior)
{
    u16 headerId;
    struct Roamer * roamer;

    if (sWildEncountersDisabled == TRUE)
        return FALSE;

    headerId = GetCurrentMapWildMonHeaderId();
    if (headerId != HEADER_NONE)
    {
        if (ExtractMetatileAttribute(currMetatileAttrs, METATILE_ATTRIBUTE_ENCOUNTER_TYPE) == TILE_ENCOUNTER_LAND)
        {
            if (gWildMonHeaders[headerId].landMonsInfo == NULL)
                return FALSE;
            else if (previousMetatileBehavior != ExtractMetatileAttribute(currMetatileAttrs, METATILE_ATTRIBUTE_BEHAVIOR) && !DoGlobalWildEncounterDiceRoll())
                return FALSE;
            if (DoWildEncounterRateTest(gWildMonHeaders[headerId].landMonsInfo->encounterRate, FALSE) != TRUE)
            {
                AddToWildEncounterRateBuff(gWildMonHeaders[headerId].landMonsInfo->encounterRate);
                return FALSE;
            }

            else if (TryStartRoamerEncounter() == TRUE)
            {
                roamer = &gSaveBlock1Ptr->roamer;
                if (!IsWildLevelAllowedByRepel(roamer->level))
                {
                    return FALSE;
                }

                CreateRoamerMonInstance();
                StartRoamerBattle();
                return TRUE;
            }
            else
            {

                // try a regular wild land encounter
                if (TryGenerateWildMon(gWildMonHeaders[headerId].landMonsInfo, WILD_AREA_LAND, WILD_CHECK_REPEL) == TRUE)
                {
                    StartWildBattle();
                    return TRUE;
                }
                else
                {
                    AddToWildEncounterRateBuff(gWildMonHeaders[headerId].landMonsInfo->encounterRate);
                }
            }
        }
        else if (ExtractMetatileAttribute(currMetatileAttrs, METATILE_ATTRIBUTE_ENCOUNTER_TYPE) == TILE_ENCOUNTER_WATER
                 || (TestPlayerAvatarFlags(PLAYER_AVATAR_FLAG_SURFING) && MetatileBehavior_IsBridge(ExtractMetatileAttribute(currMetatileAttrs, METATILE_ATTRIBUTE_BEHAVIOR)) == TRUE))
        {
            if (gWildMonHeaders[headerId].waterMonsInfo == NULL)
                return FALSE;
            else if (previousMetatileBehavior != ExtractMetatileAttribute(currMetatileAttrs, METATILE_ATTRIBUTE_BEHAVIOR) && !DoGlobalWildEncounterDiceRoll())
                return FALSE;
            else if (DoWildEncounterRateTest(gWildMonHeaders[headerId].waterMonsInfo->encounterRate, FALSE) != TRUE)
            {
                AddToWildEncounterRateBuff(gWildMonHeaders[headerId].waterMonsInfo->encounterRate);
                return FALSE;
            }

            if (TryStartRoamerEncounter() == TRUE)
            {
                roamer = &gSaveBlock1Ptr->roamer;
                if (!IsWildLevelAllowedByRepel(roamer->level))
                {
                    return FALSE;
                }

                CreateRoamerMonInstance();
                StartRoamerBattle();
                return TRUE;
            }
            else // try a regular surfing encounter
            {
                if (TryGenerateWildMon(gWildMonHeaders[headerId].waterMonsInfo, WILD_AREA_WATER, WILD_CHECK_REPEL) == TRUE)
                {
                    StartWildBattle();
                    return TRUE;
                }
                else
                {
                    AddToWildEncounterRateBuff(gWildMonHeaders[headerId].waterMonsInfo->encounterRate);
                }
            }
        }
    }

    return FALSE;
}

void RockSmashWildEncounter(void)
{
    u16 headerIdx = GetCurrentMapWildMonHeaderId();
    if (headerIdx == HEADER_NONE)
        gSpecialVar_Result = FALSE;
    else if (gWildMonHeaders[headerIdx].rockSmashMonsInfo == NULL)
        gSpecialVar_Result = FALSE;
    else if (DoWildEncounterRateTest(gWildMonHeaders[headerIdx].rockSmashMonsInfo->encounterRate, TRUE) != TRUE)
        gSpecialVar_Result = FALSE;
    else if (TryGenerateWildMon(gWildMonHeaders[headerIdx].rockSmashMonsInfo, WILD_AREA_ROCKS, WILD_CHECK_REPEL) == TRUE)
    {
        StartWildBattle();
        gSpecialVar_Result = TRUE;
    }
    else
        gSpecialVar_Result = FALSE;
}

bool8 SweetScentWildEncounter(void)
{
    s16 x, y;
    u16 headerId;

    PlayerGetDestCoords(&x, &y);
    headerId = GetCurrentMapWildMonHeaderId();
    if (headerId != HEADER_NONE)
    {
        if (MapGridGetMetatileAttributeAt(x, y, METATILE_ATTRIBUTE_ENCOUNTER_TYPE) == TILE_ENCOUNTER_LAND)
        {
            if (TryStartRoamerEncounter() == TRUE)
            {
                CreateRoamerMonInstance();
                StartRoamerBattle();
                return TRUE;
            }

            if (gWildMonHeaders[headerId].landMonsInfo == NULL)
                return FALSE;

            TryGenerateWildMon(gWildMonHeaders[headerId].landMonsInfo, WILD_AREA_LAND, 0);

            StartWildBattle();
            return TRUE;
        }
        else if (MapGridGetMetatileAttributeAt(x, y, METATILE_ATTRIBUTE_ENCOUNTER_TYPE) == TILE_ENCOUNTER_WATER)
        {
            if (TryStartRoamerEncounter() == TRUE)
            {
                CreateRoamerMonInstance();
                StartRoamerBattle();
                return TRUE;
            }

            if (gWildMonHeaders[headerId].waterMonsInfo == NULL)
                return FALSE;

            TryGenerateWildMon(gWildMonHeaders[headerId].waterMonsInfo, WILD_AREA_WATER, 0);
            StartWildBattle();
            return TRUE;
        }
    }

    return FALSE;
}

