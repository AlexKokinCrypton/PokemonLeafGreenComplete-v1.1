// PLG Complete: only the targeted rare Safari species are raised from 1% to 3%.
// In LeafGreen's four Safari land tables the relevant 1% encounter is slot 11:
// Center = Chansey, East = Pinsir, North = Tauros, West = Kangaskhan.
// Borrow 2 percentage points from the 20% common slot; slot 10 (Paras/Venonat) stays 1%.
static u8 AdjustPLGSafariLandSlot(const struct WildPokemonInfo *info, u8 slot)
{
    u16 rareSpecies;

    if (!FlagGet(FLAG_SYS_SAFARI_MODE) || slot != 0)
        return slot;

    rareSpecies = info->wildPokemon[11].species;
    if (rareSpecies != SPECIES_CHANSEY
     && rareSpecies != SPECIES_PINSIR
     && rareSpecies != SPECIES_TAUROS
     && rareSpecies != SPECIES_KANGASKHAN)
        return slot;

    // Slot 0 is 20%; redirect 2/20 of those outcomes to the targeted 1% slot.
    if (Random() % 20 < 2)
        return 11;
    return slot;
}

