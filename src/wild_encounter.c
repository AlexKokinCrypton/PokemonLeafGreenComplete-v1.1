#define PLG_ROD_NONE 0xFF
struct PLGExclusiveEncounter
{
    u8 mapGroup;
    u8 mapNum;
    u8 area;
    u8 rod;
    u16 species;
    u8 minLevel;
    u8 maxLevel;
};

